#!/usr/bin/env python3
"""Sokoban Remastered: push every crate into a hole (crate and hole both vanish).

Remaster of resources/games/Single-Player/GVGAI/sokoban.yaml. Levels are themed room-and-corridor
layouts (warehouse, garden, frozen lake, crypt, quarry) generated by pushlib: holes are placed, the
crates are scrambled away from them by reverse play (pulling), and the level is then solved forward
with a search over (player, crates, holes) states. Only levels with a verified solution are emitted;
the solution length is printed and written to tools/remaster/solutions/sokoban.json so
replay_solutions.mjs can replay it in the engine.

Layout characters (besides the shared terrain chars from common):
  w wall   A avatar   b crate   h hole   . floor
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import pushlib as P  # noqa: E402

GID = "sokoban"
SCENERY = [n for n in C.SCENERY_NAMES]

LEVELS = [
    dict(name="Loading Dock", blurb="Four crates, four holes in the warehouse floor.", theme="warehouse", seed=1,
         cols=3, rows=2, w=26, h=15, boxes=4),
    dict(name="Walled Garden", blurb="Hedges, trees and four crates to sink.", theme="garden", seed=12,
         cols=3, rows=2, w=28, h=16, boxes=4),
    dict(name="Frozen Lake", blurb="Ice floes between dark water. Crates can't swim.", theme="frozen", seed=3,
         cols=4, rows=2, w=30, h=16, boxes=5),
    dict(name="Old Crypt", blurb="Tombstones clutter the burial chambers.", theme="crypt", seed=24,
         cols=3, rows=3, w=28, h=20, boxes=5),
    dict(name="Deep Quarry", blurb="Rock walls and narrow cuts. Plan every push.", theme="quarry", seed=35,
         cols=4, rows=3, w=32, h=20, boxes=6, wide=0.3),
]


ACTIONS = f'''
Actions:
{C.face_action("avatar")}
  # Absolute 4-way movement. Walking into a crate pushes it; a crate pushed into a hole fills it
  # (both vanish). Crates only slide over floor and ground decoration; scenery blocks them.
  - Name: move
{C.MOVE_INPUTS}    Behaviours:
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}, {{mov: _dest}}]}}
        Dst: {{Object: [_empty, {", ".join(C.GROUND_NAMES)}, hole]}}
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}, {{mov: _dest}}]}}
        Dst: {{Object: box, Commands: [{{cascade: _dest}}]}}
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}]}}
        Dst: {{Object: [wall, {", ".join(SCENERY)}]}}
      - Src: {{Object: box, Commands: [{{mov: _dest}}]}}
        Dst: {{Object: {C.EMPTY_OR_GROUND}}}
      - Src: {{Object: box, Commands: [{{remove: true}}, {{reward: 1}}]}}
        Dst: {{Object: hole, Commands: [{{remove: true}}]}}
'''


def objects():
    avatar = C.facing_sprites("gvgai/oryx/knight1.png", "sokoban-avatar")
    return "\nObjects:\n" + C.terrain_objects() + "".join([
        C.obj("wall", "w", 1, C.tiled("gvgai/oryx/wall3", "_"), "[0.6, 0.6, 0.6]", "triangle", 0.9),
        C.obj("hole", "h", 1, C.img("gvgai/oryx/cspell4.png"), "[0.0, 1.0, 0.0]", "square", 0.6),
        C.obj("box", "b", 2, C.img("gvgai/newset/block1.png"), "[1.0, 0.0, 0.0]", "square", 0.5),
        C.obj("avatar", "A", 2, C.imgs(avatar), "[0.2, 0.2, 0.6]", "triangle", 1.0, C.FACE_INITIAL_ACTION, tiles=4),
    ])


def validate(name, rows):
    C.check_rect(name, rows)
    assert len(C.find(rows, "A")) == 1, f"{name}: need one avatar"
    nb, nh = len(C.find(rows, "b")), len(C.find(rows, "h"))
    assert nb == nh and nb > 0, f"{name}: crates {nb} != holes {nh}"


def main():
    parts = [C.header("Sokoban Remastered", """
        Push every crate into a hole: the crate fills it and both vanish. Warehouses, walled gardens,
        a frozen lake, a crypt and a deep quarry - walls, water, hedges, trees, rocks and tombstones block
        crates; grass, sand, moss and dirt don't. Win when no crates are left.
        """.replace("        ", ""), "avatar", ["eq: [box:count, 0]"], [], background="gvgai/newset/floor2.png")]
    sols = []
    for i, spec in enumerate(LEVELS):
        t = time.time()
        rows, ground, best = P.build_goal_level(spec, vanish=True)
        validate(spec["name"], rows)
        parts.append(C.level_block(spec["name"], spec["blurb"], rows, ground))
        sols.append(best["moves"])
        print(f"{i}. {spec['name']:14s} {len(rows[0])}x{len(rows)} crates={spec['boxes']} "
              f"solution: {best['events']} pushes, {len(best['moves'])} moves ({time.time() - t:.0f}s)", file=sys.stderr)
        if "-v" in sys.argv:
            print("\n".join(rows), file=sys.stderr)
    P.write_solutions(GID, sols)
    gdy = "".join(parts) + ACTIONS + objects()
    C.emit(GID, gdy, {
        "name": "Sokoban Remastered",
        "tagline": "Sink every crate into a hole.",
        "description": "Classic crate pushing across warehouses, gardens, a frozen lake, a crypt and a quarry. "
                       "Push each crate into a hole to fill it - but crates can't be pulled, so think ahead.",
        "tags": ["puzzle", "classic-port"],
        "difficulty": "medium",
        "original": "GVGAI/sokoban.yaml",
        "accent": "#f59e0b",
        "icon": "📦",
        "controls": {"move": "move", "extra": []},
        "hud": [{"label": "Crates left", "kind": "remaining", "object": "box", "tone": "amber"},
                {"label": "Holes left", "kind": "remaining", "object": "hole", "tone": "sky"}],
        "win_text": "All holes filled!",
        "lose_text": "Stuck? Reset and try another order.",
    })


if __name__ == "__main__":
    main()
