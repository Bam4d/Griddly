#!/usr/bin/env python3
"""Sokoban II Remastered: push every crate onto a marked target. Crates on targets can be pushed off.

Remaster of resources/games/Single-Player/GVGAI/sokoban2.yaml. Levels are themed room-and-corridor
layouts (warehouse, orchard, frozen lake, crypt, hedge garden) generated by pushlib: targets are placed, the
crates are scrambled away from the targets by reverse play (pulling), and the level is then solved forward
with a search over (player, crates) states. Only levels with a verified solution are emitted;
the solution length is printed and written to apps/web/src/games/solutions/sokoban2.json so
replay_solutions.mjs can replay it in the engine.

Layout characters (besides the shared terrain chars from common):
  w wall   A avatar   b crate   B crate on target   h target   . floor
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import pushlib as P  # noqa: E402

GID = "sokoban2"
SCENERY = [n for n in C.SCENERY_NAMES]

LEVELS = [
    dict(name="Storeroom", blurb="Line the crates up on the chalk marks.", theme="warehouse", seed=101,
         cols=3, rows=2, w=26, h=15, boxes=4),
    dict(name="Orchard", blurb="Crates of apples between the fruit trees.", theme="orchard", seed=112,
         cols=3, rows=2, w=28, h=16, boxes=4),
    dict(name="Ice Floes", blurb="Push crates across the frozen lake. Don't drop them in.", theme="frozen", seed=123,
         cols=3, rows=2, w=28, h=16, boxes=5),
    dict(name="Catacombs", blurb="Offerings for the dead, one per altar.", theme="crypt", seed=134,
         cols=3, rows=3, w=28, h=20, boxes=5),
    dict(name="Hedge Court", blurb="A formal garden of hedges and paths.", theme="garden", seed=145,
         cols=4, rows=2, w=32, h=17, boxes=5),
]


ACTIONS = f'''
Actions:
{C.face_action("avatar")}
  # Absolute 4-way movement. Walking into a crate pushes it. A crate pushed onto a target becomes a
  # placed crate; pushing a placed crate off its target turns it back into a plain crate. Crates only
  # slide over floor, ground decoration and targets; scenery blocks them.
  - Name: move
{C.MOVE_INPUTS}    Behaviours:
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}, {{mov: _dest}}]}}
        Dst: {{Object: [_empty, {", ".join(C.GROUND_NAMES)}, target]}}
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}, {{mov: _dest}}]}}
        Dst: {{Object: [box, box_in_place], Commands: [{{cascade: _dest}}]}}
      - Src: {{Object: avatar, Commands: [{{set_tile: meta.facing}}]}}
        Dst: {{Object: [wall, {", ".join(SCENERY)}]}}
      - Src: {{Object: box, Commands: [{{mov: _dest}}]}}
        Dst: {{Object: {C.EMPTY_OR_GROUND}}}
      - Src: {{Object: [box, box_in_place], Commands: [{{mov: _dest}}, {{change_to: box_in_place}}, {{reward: 1}}]}}
        Dst: {{Object: target}}
      - Src: {{Object: box_in_place, Commands: [{{mov: _dest}}, {{change_to: box}}, {{reward: -1}}]}}
        Dst: {{Object: {C.EMPTY_OR_GROUND}}}
'''


def objects():
    avatar = C.facing_sprites("gvgai/oryx/knight1.png", "sokoban2-avatar")
    return "\nObjects:\n" + C.terrain_objects() + "".join([
        C.obj("wall", "w", 1, C.tiled("gvgai/oryx/wall3", "_"), "[0.6, 0.6, 0.6]", "triangle", 0.9),
        C.obj("target", "h", 1, C.img("gvgai/oryx/cspell4.png"), "[0.0, 1.0, 0.0]", "triangle", 0.6),
        C.obj("box", "b", 2, C.img("gvgai/newset/block2.png"), "[1.0, 0.0, 0.0]", "square", 0.5),
        C.obj("box_in_place", "B", 2, C.img("gvgai/newset/block1.png"), "[0.0, 1.0, 0.0]", "square", 0.5),
        C.obj("avatar", "A", 2, C.imgs(avatar), "[0.2, 0.2, 0.6]", "triangle", 1.0, C.FACE_INITIAL_ACTION, tiles=4),
    ])


def validate(name, rows):
    C.check_rect(name, rows)
    assert len(C.find(rows, "A")) == 1, f"{name}: need one avatar"
    nb, nh = len(C.find(rows, "b")), len(C.find(rows, "h"))
    assert nb == nh and nb > 0, f"{name}: crates {nb} != targets {nh}"


def main():
    parts = [C.header("Sokoban II Remastered", """
        Push every crate onto a marked target. Placed crates light up, but they can still be pushed off
        again. A storeroom, an orchard, ice floes, catacombs and a hedge court - walls, water, hedges,
        trees, rocks and tombstones block crates; grass, sand, moss and dirt don't. Win when every crate
        is on a target.
        """.replace("        ", ""), "avatar", ["eq: [box:count, 0]"], [], background="gvgai/newset/floor2.png")]
    sols = []
    for i, spec in enumerate(LEVELS):
        t = time.time()
        rows, ground, best = P.build_goal_level(spec, vanish=False)
        validate(spec["name"], rows)
        parts.append(C.level_block(spec["name"], spec["blurb"], rows, ground))
        sols.append(best["moves"])
        print(f"{i}. {spec['name']:14s} {len(rows[0])}x{len(rows)} crates={spec['boxes']} "
              f"solution: {best['events']} pushes, {len(best['moves'])} moves ({time.time() - t:.0f}s)", file=sys.stderr)
        if "-v" in sys.argv:
            print("\n".join(rows), file=sys.stderr)
    P.write_solutions(GID, sols)
    gdy = "".join(parts) + ACTIONS + objects()
    C.emit(GID, gdy, {
        "name": "Sokoban II Remastered",
        "tagline": "Every crate on its mark.",
        "description": "Push crates onto the marked targets across storerooms, orchards, ice floes, catacombs "
                       "and hedge courts. Placed crates can be pushed off again, so order matters.",
        "tags": ["puzzle", "classic-port"],
        "difficulty": "medium",
        "original": "GVGAI/sokoban2.yaml",
        "accent": "#22d3ee",
        "icon": "🎯",
        "controls": {"move": "move", "extra": []},
        "hud": [{"label": "Crates to place", "kind": "remaining", "object": "box", "tone": "amber"},
                {"label": "Placed", "kind": "count", "object": "box_in_place", "tone": "emerald"}],
        "win_text": "Every crate is on its mark!",
        "lose_text": "Stuck? Reset and try another order.",
    })

if __name__ == "__main__":
    main()
