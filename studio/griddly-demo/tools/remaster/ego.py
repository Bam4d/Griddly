"""Helpers for the egocentric (rotating, partially observable) remastered games: torchlight, nightgarden.

These games differ from the phase-1 remasters in one way the demo cares about: the avatar is RELATIVE.
It has an orientation, `move` 1 turns left, 2 steps forward, 3 turns right, 4 steps back (keeping the
facing), and the main cameras rotate with it so "up" is always forward. meta.controls.scheme = "relative".

  * header()          cameras: Sprite2D (whole map; every oriented object incl. the avatar is drawn
                      rotated), EgoView 9x9 (OffsetY 2) and EgoClose 7x7 (track + rotate with the avatar) and
                      FollowCam 15x11 (tracks, no rotation). The agent's default Player.Observer is
                      the same 9x9 egocentric window (OffsetY 2).
  * REL_MOVE_INPUTS   relative inputs 1-4 (MetaData fwd=1 on forward, so rules can require it).
  * WAIT_ACTION       `wait` (id 1): stand still for one tick (UI: Space).
  * sync_action()     writes the avatar's x/y/facing into globals ax/ay/adx/ady after every move so
                      NPC logic can compute "am I in front of the player" (no A*/Trigger needed).
  * level_block()     like common.level_block but avatars/NPCs can carry an initial orientation,
                      written `A[R]` (U/D/L/R; parsed by MapGenerator.cpp READ_INITIAL_ORIENTATION).
                      Never put an oriented object in the last column (the map parser drops it there).

Engine notes (verified in the WASM build, Nov 2026):
  * OffsetY on avatar-tracking SPRITE_2D observers was fixed in vibe_main 3d19bc45; EgoView and the
    Player.Observer use OffsetY = EGO_OFFSET_Y (see further ahead), EgoClose stays centred.
  * `exec` with `Search:` (A*) crashes the WASM build; NPCs here steer greedily from the globals.
  * `exec: {ActionId: <variable>}` works, so NPC logic can pick a direction at run time.
"""
from __future__ import annotations

import common as C

EGO = (9, 9)
EGO_CLOSE = (7, 7)
EGO_OFFSET_Y = 2  # EgoView / Player.Observer look further ahead: the avatar sits 2 rows below the centre
FOLLOW = (15, 11)

# common.obj() shares each object's sprite with every name in C.CAMERAS
C.CAMERAS = ["EgoView", "EgoClose", "FollowCam"]

GLOBALS = ["ax", "ay", "adx", "ady"]


def header(name: str, description: str, avatar: str, win: list[str], lose: list[str], background: str,
           variables: str = "") -> str:
    bg = C.BACKGROUNDS.get(background, background)
    desc = "\n".join("    " + line for line in description.strip().splitlines())
    gl = "".join(f"    - Name: {v}\n      InitialValue: 0\n" for v in GLOBALS) + variables
    win_block = "".join(f"      - {w}\n" for w in win)
    lose_block = "".join(f"      - {lc}\n" for lc in lose)

    def cam(w, h, rot, oy=0):
        return (f"      Type: SPRITE_2D\n      TileSize: 24\n      BackgroundTile: {bg}\n"
                f"      TrackAvatar: true\n      RotateWithAvatar: {str(rot).lower()}\n      RotateAvatarImage: true\n"
                f"      Width: {w}\n      Height: {h}\n      OffsetY: {oy}\n")
    # (OffsetY is always written: named observers inherit unset values from Player.Observer)

    return f'''Version: "0.1"
Environment:
  Name: {name}
  Description: |
{desc}
    Generated by studio/griddly-demo/tools/remaster — edit the generator, not this file.
  # Cameras are observers. The demo picks one by name and the engine renders it.
  #   Sprite2D   whole level (global observer); oriented objects are drawn rotated
  #   EgoView    {EGO[0]}x{EGO[1]} first-person window: follows AND rotates with the avatar (forward = up), avatar {EGO_OFFSET_Y} rows below centre
  #   EgoClose   {EGO_CLOSE[0]}x{EGO_CLOSE[1]} first-person window
  #   FollowCam  {FOLLOW[0]}x{FOLLOW[1]} window that follows the avatar without rotating
  # The agent's default observation (Player.Observer) is the {EGO[0]}x{EGO[1]} egocentric window.
  Observers:
    Sprite2D:
      TileSize: 24
      BackgroundTile: {bg}
      RotateAvatarImage: true
      TrackAvatar: false
    EgoView:
{cam(*EGO, True, EGO_OFFSET_Y)}    EgoClose:
{cam(*EGO_CLOSE, True)}    FollowCam:
{cam(*FOLLOW, False)}    Block2D:
      TileSize: 24
  Variables:
{gl}  Player:
    Observer:
      TrackAvatar: true
      RotateWithAvatar: true
      RotateAvatarImage: true
      Width: {EGO[0]}
      Height: {EGO[1]}
      OffsetY: {EGO_OFFSET_Y}
    AvatarObject: {avatar}
  Termination:
    Win:
{win_block}    Lose:
{lose_block}  Levels:
'''


