def level_block(name: str, blurb: str, rows: list[str], ground: list[list[str]] | None = None) -> str:
    """One `Levels` entry. Cells with ground decoration under an object are written as `g/o`."""
    lines = []
    for y, r in enumerate(rows):
        toks = []
        for x, c in enumerate(r):
            g = ground[y][x] if ground else ""
            if c == ".":
                toks.append(g or ".")
            elif g and c not in TERRAIN_CHARS:
                toks.append(f"{g}/{c}")
            else:
                toks.append(c)
        lines.append(" ".join(t.ljust(3) for t in toks).rstrip())
    body = "\n".join("      " + line for line in lines)
    return f"    # {name} | {blurb}\n    - |\n{body}\n"


