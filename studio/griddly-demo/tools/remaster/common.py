class Map:
    def __init__(self, w: int, h: int, seed: int, fill: str = ".", border: str | None = "w"):
        self.w, self.h, self.rng = w, h, random.Random(seed)
        self.g = [[fill] * w for _ in range(h)]
        if border:
            self.rect(0, 0, w - 1, h - 1, border, filled=False)

    def inside(self, x, y, margin=1):
        return margin <= x < self.w - margin and margin <= y < self.h - margin

    def get(self, x, y):
        return self.g[y][x]

    def set(self, x, y, c, margin=1):
        if self.inside(x, y, margin):
            self.g[y][x] = c

    def rect(self, x0, y0, x1, y1, c, filled=True):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if filled or x in (x0, x1) or y in (y0, y1):
                    self.set(x, y, c, margin=0)

    def blob(self, cx, cy, r, c, jitter=0.35, only=None):
        for y in range(int(cy - r - 1), int(cy + r + 2)):
            for x in range(int(cx - r - 1), int(cx + r + 2)):
                if not self.inside(x, y):
                    continue
                d = ((x - cx) ** 2 + ((y - cy) * 1.15) ** 2) ** 0.5
                if d <= r * (1 - jitter / 2 + self.rng.random() * jitter) and (only is None or self.g[y][x] in only):
                    self.g[y][x] = c

    def walk(self, p0, p1, c, width=1, wobble=0.35, only=None):
        """Biased random walk from p0 to p1 painting a brush (rivers, tunnels, paths)."""
        x, y = p0
        tx, ty = p1
        for _ in range(4 * (self.w + self.h)):
            for dy in range(-width + 1, width):
                for dx in range(-width + 1, width):
                    if self.inside(x + dx, y + dy) and (only is None or self.g[y + dy][x + dx] in only):
                        self.g[y + dy][x + dx] = c
            if (x, y) == (tx, ty):
                return
            if self.rng.random() < wobble:
                x += self.rng.choice((-1, 0, 1))
                y += self.rng.choice((-1, 0, 1))
            elif abs(tx - x) > abs(ty - y) or (abs(tx - x) == abs(ty - y) and self.rng.random() < 0.5):
                x += (tx > x) - (tx < x)
            else:
                y += (ty > y) - (ty < y)
            x = min(max(x, 1), self.w - 2)
            y = min(max(y, 1), self.h - 2)

    def maze(self, x0, y0, x1, y1, wall="w", braid=0.5):
        """Perfect maze (1-wide corridors) in the box, then braid dead ends into loops."""
        self.rect(x0, y0, x1, y1, wall)
        cells = [(x, y) for y in range(y0 + 1, y1, 2) for x in range(x0 + 1, x1, 2)]
        cellset = set(cells)
        start = self.rng.choice(cells)
        seen, stack = {start}, [start]
        self.g[start[1]][start[0]] = "."
        while stack:
            x, y = stack[-1]
            nbrs = [(x + dx, y + dy) for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2))
                    if (x + dx, y + dy) in cellset and (x + dx, y + dy) not in seen]
            if not nbrs:
                stack.pop()
                continue
            nx, ny = self.rng.choice(nbrs)
            self.g[(y + ny) // 2][(x + nx) // 2] = "."
            self.g[ny][nx] = "."
            seen.add((nx, ny))
            stack.append((nx, ny))
        for x, y in cells:
            walls = [(dx, dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
                     if self.g[y + dy][x + dx] == wall and x0 < x + 2 * dx < x1 and y0 < y + 2 * dy < y1]
            if len(walls) >= 3 and self.rng.random() < braid:
                dx, dy = self.rng.choice(walls)
                self.g[y + dy][x + dx] = "."

    def free(self, region=None, ch="."):
        x0, y0, x1, y1 = region or (1, 1, self.w - 2, self.h - 2)
        return [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1) if self.g[y][x] == ch]

    def scatter(self, c, n, region=None, away_from=None, min_dist=0, clear=0):
        """Place n of c on free floor, optionally away from a point and with `clear` free neighbours."""
        spots = self.free(region)
        self.rng.shuffle(spots)
        placed = []
        for x, y in spots:
            if len(placed) >= n:
                break
            if away_from and abs(x - away_from[0]) + abs(y - away_from[1]) < min_dist:
                continue
            if clear and sum(self.g[y + dy][x + dx] == "." for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))) < clear:
                continue
            self.g[y][x] = c
            placed.append((x, y))
        return placed

    def rows(self, solid: str = "w") -> list[str]:
        """Rows, cropped so at most one fully-solid ring surrounds the playable area.

        `solid` = the characters that count as solid border (the game's wall char(s)); terrain
        structure (water, rock, hedge, stone) always counts.
        """
        g = self.g
        sol = set(solid) | STRUCTURE_SCENERY
        is_solid = lambda c: c in sol
        top = next(y for y in range(self.h) if not all(is_solid(c) for c in g[y]))
        bot = next(y for y in reversed(range(self.h)) if not all(is_solid(c) for c in g[y]))
        left = next(x for x in range(self.w) if not all(is_solid(g[y][x]) for y in range(self.h)))
        right = next(x for x in reversed(range(self.w)) if not all(is_solid(g[y][x]) for y in range(self.h)))
        y0, y1 = max(top - 1, 0), min(bot + 1, self.h - 1)
        x0, x1 = max(left - 1, 0), min(right + 1, self.w - 1)
        return ["".join(r[x0:x1 + 1]) for r in g[y0:y1 + 1]]


def decorate(rows: list[str], recipe: dict, seed: int, floor: str = ".", stack_under: str = "") -> list[list[str]]:
    """Ground decoration layer: one of '' or a GROUND char per cell.

    Patches of grass / moss / dirt / sand go on `floor` cells and (if listed in `stack_under`) under
    those object chars (e.g. the avatar, boxes, enemies). Small props (bones, mushrooms, skulls) only
    go on bare floor. recipe keys: grass, moss, dirt, sand (number of patches), bones, mush, skull
    (number of props).
    """
    rng = random.Random(seed)
    h, w = len(rows), len(rows[0])
    ground = [[""] * w for _ in range(h)]
    ok = set(floor) | set(stack_under)
    cells = [(x, y) for y in range(h) for x in range(w) if rows[y][x] in ok]
    if not cells:
        return ground
    cellset = set(cells)

    def patch(char, count, rmin, rmax):
        for _ in range(count):
            cx, cy = rng.choice(cells)
            r = rng.uniform(rmin, rmax)
            for x in range(int(cx - r - 1), int(cx + r + 2)):
                for y in range(int(cy - r - 1), int(cy + r + 2)):
                    if (x, y) not in cellset:
                        continue
                    d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
                    if d <= r and rng.random() < 1.15 - d / (r + 0.01) * 0.6:
                        ground[y][x] = char

    patch(GROUND_CHARS["sand"], recipe.get("sand", 0), 1.2, 3.0)
    patch(GROUND_CHARS["dirt"], recipe.get("dirt", 0), 1.0, 2.8)
    patch(GROUND_CHARS["moss"], recipe.get("moss", 0), 1.0, 3.0)
    patch(GROUND_CHARS["grass"], recipe.get("grass", 0), 1.2, 3.4)
    for y in range(h):  # grass grows around trees and bushes
        for x in range(w):
            if rows[y][x] in (SCENERY_CHARS["tree"], SCENERY_CHARS["bush"]):
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    if (x + dx, y + dy) in cellset and rng.random() < 0.5:
                        ground[y + dy][x + dx] = GROUND_CHARS["grass"]
    props = [(GROUND_CHARS["mushroom"], "mush"), (GROUND_CHARS["skull"], "skull"), (GROUND_CHARS["bones"], "bones")]
    for char, key in props:
        free = [(x, y) for x, y in cells if rows[y][x] in floor and ground[y][x] in ("", GROUND_CHARS["moss"],
                                                                                    GROUND_CHARS["dirt"])]
        for x, y in rng.sample(free, min(recipe.get(key, 0), len(free))):
            ground[y][x] = char
    return ground


def reach(rows: list[str], start: tuple[int, int], passable) -> set[tuple[int, int]]:
    """4-connected flood fill from start over cells where passable(char, (x, y)) is true."""
    seen, q = {start}, collections.deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if n in seen or not (0 <= n[1] < len(rows) and 0 <= n[0] < len(rows[0])):
                continue
            if passable(rows[n[1]][n[0]], n):
                seen.add(n)
                q.append(n)
    return seen


def find(rows: list[str], ch: str) -> list[tuple[int, int]]:
    return [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == ch]


def check_rect(name: str, rows: list[str]):
    w = len(rows[0])
    assert all(len(r) == w for r in rows), f"{name}: ragged rows {[len(r) for r in rows]}"


