def emit(game_id: str, gdy: str, meta: dict):
    """Write the GDY (repo + demo copy) and the demo catalog metadata.

    meta keys (all strings unless noted):
      name, tagline (one line), description (2-3 sentences), tags (list: e.g. puzzle, action,
      maze, exploration, stealth, classic-port), difficulty ("easy"|"medium"|"hard"),
      original (path of the game this remasters, e.g. "GVGAI/sokoban.yaml"),
      accent (tailwind-ish hex colour for the card, e.g. "#34d399"), icon (one emoji),
      controls: {"move": "move", "extra": [{"key": " ", "label": "Attack", "action": "attack",
                 "directional": true}]},
      hud: list of {"label", "kind": "collected"|"remaining"|"count"|"var"|"global",
                    "object", "variable"?, "tone": "fuchsia"|"amber"|"rose"|"sky"|"emerald"}
      win_text, lose_text.
    Level names/blurbs come from the `# Name | blurb` comments emitted by level_block().
    """
    GAMES_DIR.mkdir(parents=True, exist_ok=True)
    WEB_GAMES.mkdir(parents=True, exist_ok=True)
    (GAMES_DIR / f"{game_id}.yaml").write_text(gdy)
    (WEB_GAMES / f"{game_id}.yaml").write_text(gdy)
    meta = {"id": game_id, **meta}
    (WEB_GAMES / f"{game_id}.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {game_id}: {GAMES_DIR.relative_to(ROOT)}/{game_id}.yaml (+ demo copy, meta)", file=sys.stderr)
