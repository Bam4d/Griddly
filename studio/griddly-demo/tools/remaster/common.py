def load_png(path: Path) -> tuple[int, int, list[list[tuple[int, int, int, int]]]]:
    d = path.read_bytes()
    i, idat, pal, trns = 8, b"", None, None
    while i < len(d):
        n, t = struct.unpack(">I4s", d[i:i + 8])
        c = d[i + 8:i + 8 + n]
        i += 12 + n
        if t == b"IHDR":
            w, h, bd, ct, _, _, il = struct.unpack(">IIBBBBB", c)
        elif t == b"PLTE":
            pal = [tuple(c[j:j + 3]) for j in range(0, len(c), 3)]
        elif t == b"tRNS":
            trns = c
        elif t == b"IDAT":
            idat += c
    assert il == 0, f"{path}: interlaced PNG not supported"
    chans = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ct]
    bpp = max(1, chans * bd // 8)
    stride = (w * chans * bd + 7) // 8
    raw = zlib.decompress(idat)
    prev = bytearray(stride)
    out = []
    k = 0
    for _ in range(h):
        f = raw[k]
        line = bytearray(raw[k + 1:k + 1 + stride])
        k += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            cc = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - cc
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - cc)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else cc)) & 255
        prev = line
        if bd < 8:
            per = 8 // bd
            vals = [(line[x // per] >> (8 - bd * (x % per + 1))) & ((1 << bd) - 1) for x in range(w)]
        elif bd == 8:
            vals = None
        else:
            raise ValueError(f"{path}: {bd}-bit PNG not supported")
        row = []
        for x in range(w):
            if ct == 3:
                idx = vals[x] if vals else line[x]
                r, g, b = pal[idx]
                al = trns[idx] if trns and idx < len(trns) else 255
            elif ct == 0:
                v = vals[x] * (255 // ((1 << bd) - 1)) if vals else line[x]
                r = g = b = v
                al = 255
            elif ct == 2:
                r, g, b = line[x * 3:x * 3 + 3]
                al = 255
            elif ct == 4:
                r = g = b = line[x * 2]
                al = line[x * 2 + 1]
            else:
                r, g, b, al = line[x * 4:x * 4 + 4]
            row.append((r, g, b, al))
        out.append(row)
    return w, h, out


def save_png(path: Path, w: int, h: int, px: list[list[tuple[int, int, int, int]]]):
    raw = b"".join(b"\x00" + bytes(v for p in row for v in p) for row in px)
    chunk = lambda t, data: struct.pack(">I", len(data)) + t + data + struct.pack(">I", zlib.crc32(t + data) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def _in_tri(px, py, a, b, c):
    def s(p1, p2, p3):
        return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
    d1, d2, d3 = s((px, py), a, b), s((px, py), b, c), s((px, py), c, a)
    neg = d1 < 0 or d2 < 0 or d3 < 0
    pos = d1 > 0 or d2 > 0 or d3 > 0
    return not (neg and pos)


def facing_sprites(src: str, stem: str) -> list[str]:
    """Write resources/images/remastered/<stem>-{up,right,down,left}.png: the source sprite with a
    small yellow direction arrow at the matching tile edge. Returns the 4 image paths (relative to
    resources/images) in render-tile order up, right, down, left."""
    w, h, base = load_png(IMAGES_DIR / src)
    s = w / 24.0
    out = []
    for d in ("up", "right", "down", "left"):
        px = [list(r) for r in base]
        for y in range(h):
            for x in range(w):
                cx, cy = x + 0.5, y + 0.5
                # map into the "up" frame: u across the edge, v = distance from the arrow's edge
                if d == "up":
                    u, v = cx, cy
                elif d == "right":
                    u, v = cy, w - cx
                elif d == "down":
                    u, v = w - cx, h - cy
                else:
                    u, v = h - cy, cx
                mid = w / 2.0
                outer = ((mid, 0.0), (mid - 5.0 * s, 6.5 * s), (mid + 5.0 * s, 6.5 * s))
                inner = ((mid, 1.2 * s), (mid - 3.4 * s, 5.6 * s), (mid + 3.4 * s, 5.6 * s))
                if _in_tri(u, v, *inner):
                    px[y][x] = (250, 204, 21, 255)
                elif _in_tri(u, v, *outer):
                    px[y][x] = (28, 25, 23, 255)
        rel = f"remastered/{stem}-{d}.png"
        save_png(IMAGES_DIR / rel, w, h, px)
        out.append(rel)
    return out


