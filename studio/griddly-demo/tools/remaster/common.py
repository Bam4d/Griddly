def img(path: str) -> str:
    return f"        - Image: {path}"


def imgs(paths: list[str]) -> str:
    return "\n".join(img(p) for p in paths)


def tiled(prefix: str, sep: str = "-") -> str:
    """WALL_16 auto-tiled sprite from 16 images <prefix><sep>0..15.png."""
    lst = "\n".join(f"            - {prefix}{sep}{i}.png" for i in range(16))
    return f"        - TilingMode: WALL_16\n          Image:\n{lst}"


