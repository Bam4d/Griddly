"""Shared helpers for the "Remastered" single-player Griddly games.

Every remastered game is generated by `tools/remaster/<game_id>.py`, which imports this module and
calls `emit(...)`. The generator owns the levels and rules; this module provides:

  * `Map`            grid painting primitives (rects, organic blobs, rivers/walks, braided mazes,
                     scatter) on a seeded RNG, plus cropping.
  * terrain          a shared library of walkable ground (grass, moss, dirt, sand, bones, mushrooms,
                     skulls, bridges) and solid scenery (water, trees, bushes, rock, hedges,
                     tombstones, torches) with reserved map characters, and `decorate()` to sprinkle
                     ground patches onto a level.
  * `facing_sprites` builds the 4 avatar facing sprites (up/right/down/left) with a direction arrow
                     baked in, written to resources/images/remastered/.
  * GDY builders     `header()` (cameras = named observers, termination, levels header), `obj()`
                     (object with sprites shared by every camera), `level_block()`, `MOVE_INPUTS`.
  * `reach()`        BFS reachability for validation.
  * `emit()`         writes the GDY to resources/games/Single-Player/Remastered/<id>.yaml, the demo's
                     bundled copy, and the demo catalog metadata JSON.

Conventions every remastered game follows (the demo UI relies on them):
  * Object Z: ground terrain Z=0; everything else Z>=1 (so it can stand on ground).
  * Any rule whose destination is `_empty` must use EMPTY_OR_GROUND instead, so things can move
    onto ground decoration.
  * The avatar moves with the `move` action using MOVE_INPUTS (1 left, 2 up, 3 right, 4 down,
    absolute, MetaData.facing) and every avatar `move` behaviour includes `set_tile: meta.facing`;
    the avatar's render tiles 0..3 are the facing sprites (up, right, down, left). Use
    FACE_ACTION + `face_initial_action()` to start facing down.
  * Extra player actions that need a direction (e.g. attack) also use MOVE_INPUTS; the UI sends the
    last movement direction.
"""
