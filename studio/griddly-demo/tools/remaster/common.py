def obj(name: str, char: str | None, z: int, sprite: str, color: str = "[0.6, 0.6, 0.6]", shape: str = "square",
        scale: float = 0.9, extra: str = "", tiles: int = 1) -> str:
    """An object definition whose Sprite2D is shared by every camera (YAML anchor).

    `sprite` is one or more `        - Image: ...` / tiled() entries. `tiles` = number of render tiles
    (needed for Block2D when the object uses set_tile). `extra` is raw YAML (Variables,
    InitialActions) indented by 4 spaces.
    """
    shared = "".join(f"      {cam}: *{name}_sprite\n" for cam in CAMERAS)
    block = "\n".join(f"        - Shape: {shape}\n          Color: {color}\n          Scale: {scale}" for _ in range(tiles))
    mc = f"    MapCharacter: {json.dumps(char)}\n" if char else ""
    return (f"  - Name: {name}\n{mc}    Z: {z}\n{extra}    Observers:\n      Sprite2D: &{name}_sprite\n{sprite}\n"
            f"{shared}      Block2D:\n{block}\n")


